export type PublicCopyKey = keyof typeof publicCopy[Languages.ENGLISH];
export type TranslatePublicCopy = (key: PublicCopyKey, params?: Record<string, string | number>) => string;

type PublicLanguageContextValue = {
    language: Languages;
    languageCode: PublicLanguageCode;
    setLanguage: (language: Languages) => void;
    t: TranslatePublicCopy;
};

const PublicLanguageContext = createContext<PublicLanguageContextValue>({
    language: Languages.ENGLISH,
    languageCode: "en",
    setLanguage: () => undefined,
    t: (key, params) => interpolate(publicCopy[Languages.ENGLISH][key], params),
});

export function PublicLanguageProvider({
    productId,
    defaultLanguage,
    children,
}: {
    productId: string;
    defaultLanguage?: Languages | string;
    children: ReactNode;
}) {
    const [language, setLanguageState] = useState<Languages>(() => resolveInitialPublicLanguage(productId, defaultLanguage));

    useEffect(() => {
        setLanguageState(resolveInitialPublicLanguage(productId, defaultLanguage));
    }, [productId, defaultLanguage]);

    useEffect(() => {
        document.documentElement.lang = PUBLIC_LANGUAGES[language].code;
    }, [language]);

    const setLanguage = useCallback((nextLanguage: Languages) => {
        const normalized = normalizePublicLanguage(nextLanguage);
        setLanguageState(normalized);
        storeVisitorLanguage(productId, normalized);
        writeLanguageToUrl(normalized);
    }, [productId]);

    const t = useCallback<TranslatePublicCopy>((key, params) => {
        const value = (publicCopy[language] as Partial<Record<PublicCopyKey, string>>)[key] || publicCopy[Languages.ENGLISH][key] || key;
        return interpolate(value, params);
    }, [language]);

    const value = useMemo<PublicLanguageContextValue>(() => ({
        language,
        languageCode: PUBLIC_LANGUAGES[language].code,
        setLanguage,
        t,
    }), [language, setLanguage, t]);

    return <PublicLanguageContext.Provider value={value}>{children}</PublicLanguageContext.Provider>;
}

export function usePublicLanguage() {
    return useContext(PublicLanguageContext);
}

export function normalizePublicLanguage(value?: string | Languages | null): Languages {
    return Object.values(Languages).includes(value as Languages) ? value as Languages : Languages.ENGLISH;
}

export function parsePublicLanguageCode(value?: string | null): Languages | null {
    if (!value) return null;
    return languageByCode[value.toLowerCase() as PublicLanguageCode] || null;
}

export function getPublicLanguageStorageKey(productId: string) {
    return `flexpayz.publicLanguage.${productId || "unknown"}`;
}

export function getPublicLanguageUrlParam(language: Languages) {
    return PUBLIC_LANGUAGES[normalizePublicLanguage(language)].code;
}

export function withPublicLanguageParam(href: string, language: Languages) {
    const code = getPublicLanguageUrlParam(language);
    const url = new URL(href, window.location.origin);
    url.searchParams.set("lang", code);
    return `${url.pathname}${url.search}${url.hash}`;
}

function resolveInitialPublicLanguage(productId: string, defaultLanguage?: Languages | string) {
    const urlLanguage = parsePublicLanguageCode(new URLSearchParams(window.location.search).get("lang"));
    if (urlLanguage) {
        storeVisitorLanguage(productId, urlLanguage);
        return urlLanguage;
    }

    const storedLanguage = readStoredVisitorLanguage(productId);
    if (storedLanguage) return storedLanguage;

    return normalizePublicLanguage(defaultLanguage);
}

function readStoredVisitorLanguage(productId: string) {
    try {
        const storedValue = window.localStorage.getItem(getPublicLanguageStorageKey(productId));
        if (!storedValue) return null;
        const storedCode = parsePublicLanguageCode(storedValue);
        if (storedCode) return storedCode;
        return Object.values(Languages).includes(storedValue as Languages) ? storedValue as Languages : null;
    } catch {
        return null;
    }
}

function storeVisitorLanguage(productId: string, language: Languages) {
    try {
        window.localStorage.setItem(getPublicLanguageStorageKey(productId), getPublicLanguageUrlParam(language));
    } catch {
        return;
    }
}

function writeLanguageToUrl(language: Languages) {
    const url = new URL(window.location.href);
    url.searchParams.set("lang", getPublicLanguageUrlParam(language));
    window.history.replaceState(window.history.state, "", `${url.pathname}${url.search}${url.hash}`);
}

function interpolate(value: string, params?: Record<string, string | number>) {
    if (!params) return value;
    return Object.entries(params).reduce((text, [key, replacement]) => text.split(`{${key}}`).join(String(replacement)), value);
}
